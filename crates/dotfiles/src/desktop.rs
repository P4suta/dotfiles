/// The binaries inside the Mac app bundles, which the bundles keep off `PATH`.
pub const GHOSTTY_BUNDLE_BINARY: &str = "/Applications/Ghostty.app/Contents/MacOS/ghostty";
const TAILSCALE_BUNDLE_BINARY: &str = "/Applications/Tailscale.app/Contents/MacOS/Tailscale";

/// The vendors' installers and release downloads.
const KITTY_INSTALLER: &str = "https://sw.kovidgoyal.net/kitty/installer.sh";
const ZED_INSTALLER: &str = "https://zed.dev/install.sh";
const NERD_FONTS_RELEASES: &str = "https://github.com/ryanoasis/nerd-fonts/releases/download";

fn text(data: &serde_json::Value, pointer: &str) -> Result<String> {
    Ok(data
        .pointer(pointer)
        .and_then(serde_json::Value::as_str)
        .with_context(|| format!("desktop setting is missing: {pointer}"))?
        .to_owned())
}

pub(crate) fn refresh(context: &ContextData, runner: &mut impl Runner) -> Result<()> {
    match context.profile {
        Profile::Mac => mac(context, runner),
        Profile::Linux => linux(context, runner),
        #[cfg(windows)]
        Profile::Windows => crate::windows::steps::run(context, crate::setup::Step::Desktop),
        #[cfg(not(windows))]
        Profile::Windows => anyhow::bail!("the Windows desktop refresh runs only on Windows"),
        Profile::Wsl => Ok(()),
    }
}

/// Launchers the earlier Linux and Mac repositories wrote for the same bundle, which this one takes over byte for byte.
#[must_use]
pub fn earlier_bundle_launchers(binary: &Path) -> [Vec<u8>; 2] {
    [
        format!("#!/bin/sh\nexec {} \"$@\"\n", binary.display()).into_bytes(),
        format!(
            "#!/usr/bin/env bash\n# Generated by dotfiles-refresh-desktop. Edit the generator, not this file.\nexec \"{}\" \"$@\"\n",
            binary.display()
        )
        .into_bytes(),
    ]
}

/// Writes a launcher at `target` that runs `binary` and takes over any launcher this or an earlier repository wrote.
///
/// # Errors
///
/// Returns an error when `target` names a directory or a launcher another tool owns, when the `binary` path lacks a UTF-8 form, or when it can't write the launcher.
pub fn bundle_shim(target: &Path, binary: &Path) -> Result<()> {
    ensure!(
        !fs::symlink_metadata(target).is_ok_and(|metadata| metadata.is_dir()),
        "bundle shim target is a directory"
    );
    let old = fs::read(target).unwrap_or_default();
    if target.is_file()
        && !old.starts_with(b"#!/bin/sh\n# dotfiles bundle launcher\n")
        && !earlier_bundle_launchers(binary).contains(&old)
        && fs::symlink_metadata(target).is_ok_and(|metadata| !metadata.is_symlink())
    {
        anyhow::bail!("refusing to replace a launcher owned by another tool");
    }
    let quoted = binary
        .to_str()
        .context("bundle path is not UTF-8")?
        .replace('\'', "'\\''");
    replace(
        target,
        format!("#!/bin/sh\n# dotfiles bundle launcher\nexec '{quoted}' \"$@\"\n").as_bytes(),
        true,
    )
}

fn mac(context: &ContextData, runner: &mut impl Runner) -> Result<()> {
    let brewfile = context.home.join(".config/homebrew/Brewfile");
    ensure!(
        runner.available(Tool::Brew) && brewfile.is_file(),
        "Homebrew and the applied Brewfile are required"
    );
    let arguments = vec![
        "bundle".into(),
        "check".into(),
        "--no-upgrade".into(),
        "--file".into(),
        brewfile.clone().into(),
    ];
    if !runner.run(Tool::Brew, &arguments)?.success {
        checked(
            runner,
            Tool::Brew,
            &[
                "bundle".into(),
                "install".into(),
                "--no-upgrade".into(),
                "--file".into(),
                brewfile.into(),
            ],
        )?;
    }
    for (tool, binary) in [
        (Tool::Ghostty, GHOSTTY_BUNDLE_BINARY),
        (Tool::Tailscale, TAILSCALE_BUNDLE_BINARY),
    ] {
        if Path::new(binary).is_file() {
            let target = context.home.join(".local/bin").join(tool.program());
            if !runner.available(tool) || target.exists() || fs::symlink_metadata(&target).is_ok() {
                bundle_shim(&target, Path::new(binary))?;
            }
        }
    }
    if runner.available(Tool::Ghostty) {
        checked(
            runner,
            Tool::Ghostty,
            &args(&["+show-config", "--default=false"]),
        )?;
    }
    Ok(())
}

fn gsetting(runner: &mut impl Runner, schema: &str, key: &str, value: &str) -> Result<()> {
    if runner.available(Tool::Gsettings) {
        let writable = runner.run(Tool::Gsettings, &args(&["writable", schema, key]))?;
        if writable.success
            && writable
                .bytes
                .strip_suffix(b"\n")
                .unwrap_or(&writable.bytes)
                == b"true"
        {
            checked(runner, Tool::Gsettings, &args(&["set", schema, key, value]))?;
        }
    }
    Ok(())
}

fn linux(context: &ContextData, runner: &mut impl Runner) -> Result<()> {
    let kitty_channel = text(&context.data, &context.platform("/desktop/kitty_channel"))?;
    ensure!(
        matches!(kitty_channel.as_str(), "stable" | "nightly"),
        "unknown Kitty channel"
    );
    let zed_channel = text(&context.data, &context.platform("/desktop/zed_channel"))?;
    let (suffix, app_id) = match zed_channel.as_str() {
        "stable" => ("", "dev.zed.Zed"),
        "preview" => ("-preview", "dev.zed.Zed-Preview"),
        "nightly" => ("-nightly", "dev.zed.Zed-Nightly"),
        "dev" => ("-dev", "dev.zed.Zed-Dev"),
        _ => anyhow::bail!("unknown Zed channel"),
    };
    let font_version = text(
        &context.data,
        &context.platform("/desktop/nerd_fonts_version"),
    )?;
    ensure!(
        font_version.starts_with('v')
            && font_version[1..]
                .bytes()
                .all(|byte| byte.is_ascii_digit() || byte == b'.'),
        "invalid Nerd Font version"
    );
    kitty(context, runner, &kitty_channel)?;
    zed(context, runner, &zed_channel, suffix, app_id)?;
    nerd_font(context, runner, &font_version)?;
    if runner.available(Tool::Gsettings) {
        gnome(context, runner)?;
    }
    optional(
        runner,
        Tool::UpdateDesktopDatabase,
        &[context
            .home
            .join(".local/share/applications")
            .to_str()
            .context("invalid applications path")?],
    );
    if runner.available(Tool::XdgMime) {
        for mime in ["text/plain", "text/markdown"] {
            checked(
                runner,
                Tool::XdgMime,
                &args(&["default", &format!("{app_id}.desktop"), mime]),
            )?;
        }
    }
    Ok(())
}

fn kitty(context: &ContextData, runner: &mut impl Runner, kitty_channel: &str) -> Result<()> {
    let destination = format!("dest={}", context.home.join(".local").display());
    let channel = format!("installer={kitty_channel}");
    let mut arguments = vec!["launch=n", destination.as_str()];
    if kitty_channel != "stable" {
        arguments.push(&channel);
    }
    crate::setup::vendor_installer(runner, KITTY_INSTALLER, &arguments)?;
    for name in ["kitty", "kitten"] {
        link(
            &context.home.join(".local/kitty.app/bin").join(name),
            &context.home.join(".local/bin").join(name),
        )?;
    }
    Ok(())
}

fn zed(
    context: &ContextData,
    runner: &mut impl Runner,
    zed_channel: &str,
    suffix: &str,
    app_id: &str,
) -> Result<()> {
    let bundle = context.home.join(format!(".local/zed{suffix}.app"));
    let binary = bundle.join("bin/zed");
    if !binary.is_file()
        || !runner
            .run_installed(&binary, &args(&["--version"]))?
            .success
    {
        let scope = tempfile::tempdir()?;
        let script = scope.path().join("zed-installer.sh");
        checked(
            runner,
            Tool::Curl,
            &[
                "--proto".into(),
                "=https".into(),
                "--tlsv1.2".into(),
                "-fsSL".into(),
                "--max-time".into(),
                "300".into(),
                ZED_INSTALLER.into(),
                "-o".into(),
                script.clone().into(),
            ],
        )?;
        checked(
            runner,
            Tool::Env,
            &[
                format!("ZED_CHANNEL={zed_channel}").into(),
                "sh".into(),
                script.into(),
            ],
        )?;
        ensure!(
            binary.is_file()
                && runner
                    .run_installed(&binary, &args(&["--version"]))?
                    .success,
            "Zed installation is incomplete or unusable"
        );
    }
    let mut desktop_source = bundle.join(format!("share/applications/{app_id}.desktop"));
    if !desktop_source.is_file() {
        desktop_source = bundle.join(format!("share/applications/zed{suffix}.desktop"));
    }
    let entry = fs::read_to_string(desktop_source)?;
    let quoted_binary = format!(
        "\"{}\"",
        binary
            .to_str()
            .context("invalid desktop executable path")?
            .replace('\\', "\\\\")
            .replace('"', "\\\"")
    );
    let desktop = entry
        .replace(
            "Icon=zed",
            &format!(
                "Icon={}",
                bundle
                    .join("share/icons/hicolor/512x512/apps/zed.png")
                    .display()
            ),
        )
        .replace("Exec=zed", &format!("Exec={quoted_binary}"));
    let desktop_target = context
        .home
        .join(format!(".local/share/applications/{app_id}.desktop"));
    replace(&desktop_target, desktop.as_bytes(), false)?;
    link(&binary, &context.home.join(".local/bin/zed"))?;
    if runner.available(Tool::DesktopFileValidate) {
        checked(
            runner,
            Tool::DesktopFileValidate,
            &[desktop_target.clone().into()],
        )?;
    }
    Ok(())
}

fn nerd_font(context: &ContextData, runner: &mut impl Runner, font_version: &str) -> Result<()> {
    let fonts = context
        .home
        .join(".local/share/fonts/JetBrainsMonoNerdFont");
    let stamp = fonts.join(".nerdfont-version");
    if !fs::read_to_string(&stamp).is_ok_and(|version| version.trim() == font_version) {
        let scope = tempfile::tempdir()?;
        let archive = scope.path().join("font.zip");
        checked(
            runner,
            Tool::Curl,
            &[
                "--proto".into(),
                "=https".into(),
                "--tlsv1.2".into(),
                "-fsSL".into(),
                "--max-time".into(),
                "300".into(),
                "-o".into(),
                archive.clone().into(),
                format!("{NERD_FONTS_RELEASES}/{font_version}/JetBrainsMono.zip").into(),
            ],
        )?;
        fs::create_dir_all(&fonts)?;
        checked(
            runner,
            Tool::Unzip,
            &[
                "-jo".into(),
                archive.into(),
                "JetBrainsMonoNerdFontMono-*.ttf".into(),
                "-d".into(),
                fonts.clone().into(),
            ],
        )?;
        replace(&stamp, format!("{font_version}\n").as_bytes(), false)?;
        if runner.available(Tool::FcCache) {
            checked(runner, Tool::FcCache, &["-f".into(), fonts.into()])?;
        }
    }
    Ok(())
}

/// The palette colors of the terminal's sixteen color slots, in slot order, as every terminal theme assigns them.
const ANSI_SLOTS: [&str; 16] = [
    "bg_dim",
    "red",
    "green",
    "yellow",
    "blue",
    "magenta",
    "cyan",
    "fg_dim",
    "bright_black",
    "red",
    "green",
    "yellow",
    "blue",
    "magenta",
    "cyan",
    "fg",
];

/// A palette color of the chezmoi data in the `rgb(r,g,b)` form `gsettings` takes.
fn palette_rgb(data: &serde_json::Value, name: &str) -> Result<String> {
    let color = data
        .pointer(&format!("/palette/{name}"))
        .and_then(serde_json::Value::as_str)
        .and_then(|literal| rules::contrast_rules::parse(literal.as_bytes()))
        .with_context(|| format!("the data holds no palette color {name}"))?;
    Ok(format!("rgb({},{},{})", color.red, color.green, color.blue))
}

/// The `gnome-terminal` profile colors and font, the keyboard repeat timing, and the Cinnamon terminal.
fn gnome(context: &ContextData, runner: &mut impl Runner) -> Result<()> {
    let profile = runner.run(
        Tool::Gsettings,
        &args(&["get", "org.gnome.Terminal.ProfilesList", "default"]),
    )?;
    if profile.success {
        let id = String::from_utf8(profile.bytes)?
            .trim()
            .trim_matches('\'')
            .to_owned();
        ensure!(
            !id.is_empty()
                && id
                    .bytes()
                    .all(|byte| byte.is_ascii_hexdigit() || byte == b'-'),
            "invalid terminal profile identifier"
        );
        let schema = format!(
            "org.gnome.Terminal.Legacy.Profile:/org/gnome/terminal/legacy/profiles:/:{id}/"
        );
        let (foreground, background) = (
            palette_rgb(&context.data, "fg")?,
            palette_rgb(&context.data, "bg")?,
        );
        for (key, value) in [
            ("use-theme-colors", "false"),
            ("foreground-color", foreground.as_str()),
            ("background-color", background.as_str()),
            ("use-transparent-background", "true"),
            ("background-transparency-percent", "15"),
            ("use-system-font", "false"),
            ("font", "JetBrainsMono Nerd Font Mono 11"),
        ] {
            gsetting(runner, &schema, key, value)?;
        }
        let slots = ANSI_SLOTS
            .iter()
            .map(|name| Ok(format!("'{}'", palette_rgb(&context.data, name)?)))
            .collect::<Result<Vec<_>>>()?;
        gsetting(
            runner,
            &schema,
            "palette",
            &format!("[{}]", slots.join(", ")),
        )?;
    }
    for schema in [
        "org.cinnamon.desktop.peripherals.keyboard",
        "org.gnome.desktop.peripherals.keyboard",
    ] {
        gsetting(runner, schema, "repeat", "true")?;
        for (key, pointer) in [
            ("delay", "/desktop/keyboard/delay"),
            ("repeat-interval", "/desktop/keyboard/repeat_interval"),
        ] {
            let value = context
                .data
                .pointer(&context.platform(pointer))
                .and_then(serde_json::Value::as_u64)
                .context("invalid keyboard timing")?;
            gsetting(runner, schema, key, &format!("uint32 {value}"))?;
        }
    }
    gsetting(
        runner,
        "org.cinnamon.desktop.default-applications.terminal",
        "exec",
        "kitty-herdr",
    )?;
    Ok(())
}

fn link(source: &Path, destination: &Path) -> Result<()> {
    if fs::symlink_metadata(destination).is_ok() {
        fs::remove_file(destination)?;
    }
    fs::create_dir_all(destination.parent().context("link parent is missing")?)?;
    #[cfg(unix)]
    std::os::unix::fs::symlink(source, destination)?;
    #[cfg(windows)]
    std::os::windows::fs::symlink_file(source, destination)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_terminal_colors_come_from_the_palette() {
        let data = serde_json::json!({"palette": {"fg": "#c0caf5", "bg": "not a color"}});
        assert_eq!(palette_rgb(&data, "fg").unwrap(), "rgb(192,202,245)");
        assert!(palette_rgb(&data, "bg").is_err());
        assert!(palette_rgb(&data, "red").is_err());
    }

    #[test]
    fn tailscale_launches_inside_its_bundle_and_does_not_overwrite_an_unrelated_binary() {
        let scope = tempfile::tempdir().unwrap();
        let shim = scope.path().join("tailscale");
        let bundle = Path::new("/Applications/Tailscale.app/Contents/MacOS/Tailscale");
        bundle_shim(&shim, bundle).unwrap();
        assert!(!fs::symlink_metadata(&shim).unwrap().is_symlink());
        assert!(
            fs::read_to_string(&shim)
                .unwrap()
                .contains("exec '/Applications/Tailscale.app/Contents/MacOS/Tailscale'")
        );
        fs::write(&shim, b"another tool").unwrap();
        assert!(bundle_shim(&shim, bundle).is_err());
        assert_eq!(fs::read(&shim).unwrap(), b"another tool");
    }
}
